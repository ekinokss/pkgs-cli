#Requires -Version 7.4
<#
.SYNOPSIS
    Deploy or update pkgs from this checkout without destructive replacement.

.DESCRIPTION
    Copies the production scripts and preview helper into the user's profile
    library, and writes a profile-less launcher. Runtime configuration and cache
    are never touched. Unrelated files in the target directory are preserved.

.PARAMETER Target
    Destination directory. Defaults to
    %USERPROFILE%\Documents\PowerShell\lib\pkgs.

.PARAMETER LauncherPath
    Launcher path. Defaults to %USERPROFILE%\bin\pkgs.cmd.

.PARAMETER ConfigureProfile
    Append the lazy `pkgs` function to the current-user PowerShell profile when
    it is not already present. Idempotent.

.PARAMETER SkipScripts
    Do not copy the production scripts (launcher only).

.PARAMETER SkipLauncher
    Do not write the profile-less launcher.

.EXAMPLE
    pwsh -NoProfile -File .\install.ps1 -WhatIf

.EXAMPLE
    pwsh -NoProfile -File .\install.ps1 -ConfigureProfile
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$Target = (Join-Path $HOME 'Documents\PowerShell\lib\pkgs'),
    [string]$LauncherPath = (Join-Path $HOME 'bin\pkgs.cmd'),
    [switch]$ConfigureProfile,
    [switch]$SkipScripts,
    [switch]$SkipLauncher
)

$ErrorActionPreference = 'Stop'
$source = $PSScriptRoot
$scripts = @(
    'pkgs.ps1'
    'pkgs-core.ps1'
    'pkgs-snapshot.ps1'
    'pkgs-model.ps1'
    'pkgs-ui.ps1'
    'pkgs-help.ps1'
    'preview.cmd'
)

if ($SkipScripts -and $SkipLauncher) {
    throw 'Nothing to do: -SkipScripts and -SkipLauncher were both supplied.'
}

function Write-Step {
    param([string]$Message)
    Write-Host "  $Message"
}

function Test-PkgsDeployment {
    param([string]$Root)
    $missing = @($scripts | Where-Object { -not (Test-Path -LiteralPath (Join-Path $Root $_)) })
    if ($missing.Count -gt 0) {
        throw "deployment incomplete; missing: $($missing -join ', ')"
    }
}

Write-Host 'pkgs installation'
Write-Host "  source  $source"
Write-Host "  target  $Target"

if (-not $SkipScripts) {
    foreach ($name in $scripts) {
        $src = Join-Path $source $name
        if (-not (Test-Path -LiteralPath $src)) {
            throw "source file missing: $src"
        }
    }

    if ($PSCmdlet.ShouldProcess($Target, 'create directory')) {
        $null = New-Item -ItemType Directory -Path $Target -Force
    }

    foreach ($name in $scripts) {
        $src = Join-Path $source $name
        $dst = Join-Path $Target $name
        if ($PSCmdlet.ShouldProcess($dst, 'copy pkgs file')) {
            Copy-Item -LiteralPath $src -Destination $dst -Force
            Write-Step "copied $name"
        }
    }

    if (-not $WhatIfPreference) {
        Test-PkgsDeployment -Root $Target
    }
}

if (-not $SkipLauncher) {
    $launcherDir = Split-Path -Parent $LauncherPath
    if ($launcherDir -and -not (Test-Path -LiteralPath $launcherDir)) {
        if ($PSCmdlet.ShouldProcess($launcherDir, 'create directory')) {
            $null = New-Item -ItemType Directory -Path $launcherDir -Force
        }
    }
    $entry = Join-Path $Target 'pkgs.ps1'
    $content = @(
        '@echo off'
        'rem Generated by pkgs install.ps1.'
        'rem Profile shells use the lazy pkgs function and shadow this shim.'
        "pwsh -NoProfile -File `"$entry`" %*"
        'exit /b %ERRORLEVEL%'
        ''
    ) -join "`r`n"

    if ($PSCmdlet.ShouldProcess($LauncherPath, 'write profile-less launcher')) {
        $null = New-Item -ItemType Directory -Path $launcherDir -Force
        Set-Content -LiteralPath $LauncherPath -Value $content -Encoding utf8NoBOM -NoNewline
        Write-Step "wrote $LauncherPath"
    }
}

if ($ConfigureProfile) {
    $marker = 'function pkgs {'
    $profilePath = $PROFILE
    $existing = if (Test-Path -LiteralPath $profilePath) {
        Get-Content -LiteralPath $profilePath -Raw
    }
    else {
        ''
    }

    if ($existing -match [regex]::Escape($marker)) {
        Write-Step 'profile already defines the lazy pkgs function; unchanged'
    }
    else {
        $snip = Join-Path $source 'integration\profile-snippet.ps1'
        if (-not (Test-Path -LiteralPath $snip)) {
            throw "profile snippet missing: $snip"
        }
        $block = @(
            ''
            '# >>> pkgs >>>'
            (Get-Content -LiteralPath $snip -Raw).TrimEnd()
            '# <<< pkgs <<<'
            ''
        ) -join "`r`n"

        if ($PSCmdlet.ShouldProcess($profilePath, 'append lazy pkgs function')) {
            $profileDir = Split-Path -Parent $profilePath
            if ($profileDir -and -not (Test-Path -LiteralPath $profileDir)) {
                $null = New-Item -ItemType Directory -Path $profileDir -Force
            }
            Add-Content -LiteralPath $profilePath -Value $block
            Write-Step "updated $profilePath"
        }
    }
}
else {
    Write-Host ''
    Write-Host 'Profile integration (optional):'
    Write-Host '  add integration\profile-snippet.ps1 to your PowerShell profile,'
    Write-Host '  or re-run with -ConfigureProfile.'
}

Write-Host ''
if (-not $WhatIfPreference -and -not $SkipScripts) {
    $pwsh = Join-Path $PSHOME 'pwsh.exe'
    try {
        $out = & $pwsh -NoProfile -File (Join-Path $Target 'pkgs.ps1') version 2>&1
        if ($LASTEXITCODE -eq 0) {
            Write-Host "Installed: $($out | Select-Object -First 1)"
        }
        else {
            Write-Warning "deployed files are in place but 'pkgs version' exited $LASTEXITCODE"
        }
    }
    catch {
        Write-Warning "deployed files are in place but verification failed: $($_.Exception.Message)"
    }
}
